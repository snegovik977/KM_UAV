def test_центроид_ведёт_обратно_к_станции(конфиг, калибровка):
    """Главное, ради чего детектор существует: центроид обязан локализоваться
    в ту точку, где станция и стоит. Ошибка здесь — это потеря 4 баллов."""
    from localization import pixel_to_ground

    истина = (1.1, -0.4)
    поза = Pose(1.0, -0.4, 2.0, 0.0, 0.0, 0.0)
    frame, _ = кадр_со_станциями([(истина[0], истина[1], "ok")], поза, конфиг)

    детектор = create_detector(конфиг, log=lambda _: None)
    детекции = детектор.detect(frame, area_m2=площадь_на_земле(поза, калибровка))
    assert len(детекции) == 1

    точка = pixel_to_ground(детекции[0].cx, детекции[0].cy, поза,
                            калибровка.intrinsics, калибровка.r_mount)
    ошибка = ((точка[0] - истина[0]) ** 2 + (точка[1] - истина[1]) ** 2) ** 0.5
    assert ошибка < 0.05, "центроид уехал на %.3f м" % ошибка


