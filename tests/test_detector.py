# -------------------------------------------------- декодирование сырых веток YOLO

def сырые_ветки(nc=3, img_size=640, бокс=(200.0, 150.0, 280.0, 260.0), класс=1):
    """Синтетические выходы RKNN с одним объектом на масштабе 80x80.

    Собираются обратной арифметикой: DFL-бины выставляются так, чтобы decode
    восстановил заданный бокс. Форма веток — как у форка airockchip.
    """
    ветки = []
    for stride in (8, 16, 32):
        сетка = img_size // stride
        box = np.zeros((1, 64, сетка, сетка), dtype=np.float32)
        cls = np.zeros((1, nc, сетка, сетка), dtype=np.float32)
        sum_ = np.zeros((1, 1, сетка, сетка), dtype=np.float32)
        if stride == 8:
            x1, y1, x2, y2 = бокс
            gx = int((x1 + x2) / 2 / stride)
            gy = int((y1 + y2) / 2 / stride)
            cx, cy = gx + 0.5, gy + 0.5
            расстояния = ((cx - x1 / stride), (cy - y1 / stride),
                          (x2 / stride - cx), (y2 / stride - cy))
            for сторона, d in enumerate(расстояния):
                # «Однобиновый» DFL: почти вся масса softmax на целом бине.
                нижний = int(d)
                box[0, сторона * 16 + нижний, gy, gx] = 40.0
            cls[0, класс, gy, gx] = 0.95
            sum_[0, 0, gy, gx] = 0.95
        ветки += [box, cls, sum_]
    return ветки


def test_decode_rawbranch_восстанавливает_бокс():
    боксы, классы, скоры = decode_rawbranch(сырые_ветки(), nc=3, img_size=640,
                                            conf=0.25, nms_thresh=0.45)
    assert боксы is not None and len(боксы) == 1
    assert int(классы[0]) == 1
    assert скоры[0] == pytest.approx(0.95, abs=1e-5)
    # Бины целочисленные, поэтому округление до stride — ожидаемая точность.
    x1, y1, x2, y2 = боксы[0]
    assert x1 == pytest.approx(200.0, abs=8.0)
    assert y2 == pytest.approx(260.0, abs=8.0)


def test_decode_rawbranch_терпит_перестановку_веток():
    """RKNN переставляет выходы, и опознавать их можно только по числу каналов.
    Опора на порядок даёт мусор вместо боксов, тоже без единой ошибки."""
    ветки = сырые_ветки()
    перемешанные = list(reversed(ветки))
    a = decode_rawbranch(ветки, 3, 640, 0.25, 0.45)
    b = decode_rawbranch(перемешанные, 3, 640, 0.25, 0.45)
    assert np.allclose(a[0], b[0])
    assert np.array_equal(a[1], b[1])


def test_decode_rawbranch_понимает_nhwc():
    """Та же ветка в раскладке NHWC обязана декодироваться одинаково."""
    ветки = сырые_ветки()
    nhwc = [t.transpose(0, 2, 3, 1) for t in ветки]
    a = decode_rawbranch(ветки, 3, 640, 0.25, 0.45)
    b = decode_rawbranch(nhwc, 3, 640, 0.25, 0.45)
    assert np.allclose(a[0], b[0])


def test_decode_rawbranch_пусто_ниже_порога():
    assert decode_rawbranch(сырые_ветки(), 3, 640, conf=0.99, nms_thresh=0.45) == (
        None, None, None)


def test_nms_склеивает_дубли():
    боксы = np.array([[0.0, 0.0, 10.0, 10.0],
                      [1.0, 1.0, 11.0, 11.0],
                      [50.0, 50.0, 60.0, 60.0]])
    скоры = np.array([0.9, 0.8, 0.7])
    оставить = nms(боксы, скоры, 0.45)
    assert sorted(оставить.tolist()) == [0, 2]
