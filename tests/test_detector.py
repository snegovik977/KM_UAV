def test_угол_длинной_стороны(конфиг, калибровка):
    """Угол панели нужен манёвру обдува (пункт 4): обдувать надо вдоль длинной
    стороны, а не только центр. minAreaRect отдаёт угол по-разному в разных версиях
    OpenCV, поэтому нормализация обязана быть нашей."""
    поза = Pose(0.0, 0.0, 2.0, 0.0, 0.0, 0.0)
    # Станция 0.35 (вдоль X) x 0.50 (вдоль Y): длинная сторона идёт по Y, то есть
    # горизонтально по кадру.
    frame, камера = кадр_со_станциями([(0.0, 0.0, "ok")], поза, конфиг)
    assert камера.station_size[1] > камера.station_size[0]

    детектор = create_detector(конфиг, log=lambda _: None)
    детекции = детектор.detect(frame, area_m2=площадь_на_земле(поза, калибровка))
    assert len(детекции) == 1
    угол = детекции[0].angle % 180.0
    assert min(угол, 180.0 - угол) < 15.0, "длинная сторона должна быть почти горизонтальна"


