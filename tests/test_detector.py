def кадр_со_станциями(станции, поза, конфиг):
    """Кадр заглушки при заданной позе дрона и расстановке станций."""
    камера = MockCamera(fps=10000.0, stations=станции, cfg=конфиг)

    class _Поза(object):
        pass

    камера.pose = lambda: поза
    return камера._синтетика(), камера


def площадь_на_земле(поза, калибровка):
    def считать(углы):
        return ground_area(углы, поза, калибровка.intrinsics, калибровка.r_mount)
    return считать


