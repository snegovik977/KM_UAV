"""Классический детектор станций на кадрах заглушки камеры.

Заглушка рисует станции той же дырочной моделью, которой локализация считает
координаты, поэтому этот тест — первая половина сквозной проверки пункта 2:
«нашёл ли детектор ровно те станции, что расставлены». Вторая половина (совпали ли
координаты) живёт в test_fusion.py.

Обученной модели у нас пока нет, поэтому вариант B (YOLO на NPU) здесь проверяется
только тем, что от него не зависит: декодированием сырых веток. Оно чистая
арифметика, и ошибка в нём даёт «ноль детекций без единой ошибки» — самый дорогой
способ потерять время на площадке (docs/lessons_from_archipelago.md §2).
"""
