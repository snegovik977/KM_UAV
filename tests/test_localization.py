# -*- coding: utf-8 -*-
"""Локализация «пиксель -> метры»: те самые 4 балла за точность подзадачи 2.3.2.

Проверить формулу глазами невозможно: перепутанный знак в R_mount даёт правдоподобные
координаты, просто зеркальные. Поэтому основной приём — round-trip: точка на земле
проецируется в пиксель обратной формулой и возвращается прямой. Расхождение обязано
быть машинным нулём, любая рассогласованность формул всплывает сразу.

Второй приём — проверка НАПРАВЛЕНИЯ: объект впереди дрона обязан оказаться в верхней
половине кадра, слева — в левой. Round-trip этого не ловит, потому что он одинаково
доволен и правильной парой формул, и одинаково зеркальной.
"""
from __future__ import annotations

import math
import random

import pytest

import config as config_module
from localization import (Pose, ground_area, ground_to_pixel, in_central_region,
                          offset_from_nadir, pixel_to_ground)
from perception.calib import Calibration, Intrinsics, from_config, mount_matrix

ШИРИНА, ВЫСОТА = 1080, 720          # ✅ фактическое разрешение борта (check_sdk.py)


def оптика(fov=60.0):
    return Intrinsics.from_fov(fov, ШИРИНА, ВЫСОТА)


def надир():
    """Идеальная надирная установка. Недостижима на железе (серва до -80),
    но нужна как эталон, в котором ответ считается в уме."""
    return mount_matrix(-90.0)


def рабочая():
    """Как на самом деле: серва -80, у камеры остаётся 10° наклона."""
    return mount_matrix(-80.0)


# ------------------------------------------------------------------ round-trip

@pytest.mark.parametrize("поза", [
    Pose(0.0, 0.0, 1.5, 0.0, 0.0, 0.0),
    Pose(1.2, -0.7, 2.0, 0.0, 0.0, 0.0),
    Pose(-0.5, 0.3, 1.8, 2.0, -3.0, 25.0),
    Pose(0.0, 0.0, 2.5, -4.5, 1.5, -110.0),
])
@pytest.mark.parametrize("серва", [-90.0, -80.0, -60.0])
def test_round_trip_машинный_ноль(поза, серва):
    """Прямая и обратная формулы обязаны быть строго обратны друг другу."""
    intr = оптика()
    r_mount = mount_matrix(серва)
    for x, y in ((0.0, 0.0), (1.0, 0.5), (-0.8, 1.3), (2.2, -1.7)):
        пиксель = ground_to_pixel(x, y, поза, intr, r_mount)
        if пиксель is None:
            continue                     # точка позади камеры — это законный отказ
        обратно = pixel_to_ground(пиксель[0], пиксель[1], поза, intr, r_mount)
        assert обратно is not None
        assert обратно[0] == pytest.approx(x, abs=1e-9)
        assert обратно[1] == pytest.approx(y, abs=1e-9)


def test_round_trip_с_дисторсией():
    """Обращение дисторсии итерацией должно сходиться, иначе координаты у краёв
    кадра поедут именно там, где они и так хуже всего."""
    intr = Intrinsics(900.0, 900.0, 540.0, 360.0, k1=-0.28, k2=0.09, p1=0.001, p2=-0.002)
    поза = Pose(0.0, 0.0, 2.0, 0.0, 0.0, 0.0)
    for x, y in ((0.0, 0.0), (0.9, 0.6), (-1.1, 0.4)):
        u, v = ground_to_pixel(x, y, поза, intr, надир())
        обратно = pixel_to_ground(u, v, поза, intr, надир())
        assert обратно[0] == pytest.approx(x, abs=1e-4)
        assert обратно[1] == pytest.approx(y, abs=1e-4)


# ------------------------------------------------------- направления, а не только числа

def test_надир_центр_кадра_под_дроном():
    intr = оптика()
    поза = Pose(1.0, -2.0, 2.0, 0.0, 0.0, 0.0)
    точка = pixel_to_ground(intr.cx, intr.cy, поза, intr, надир())
    assert точка[0] == pytest.approx(поза.x, abs=1e-9)
    assert точка[1] == pytest.approx(поза.y, abs=1e-9)


def test_надир_верх_кадра_это_вперёд():
    """Ошибка здесь разворачивает карту станций на 180° и не падает с исключением."""
    intr = оптика()
    поза = Pose(0.0, 0.0, 2.0, 0.0, 0.0, 0.0)
    впереди = ground_to_pixel(1.0, 0.0, поза, intr, надир())
    assert впереди[1] < intr.cy, "точка впереди дрона обязана быть выше центра кадра"
    assert впереди[0] == pytest.approx(intr.cx, abs=1e-9)


def test_надир_левая_часть_кадра_это_слева():
    intr = оптика()
    поза = Pose(0.0, 0.0, 2.0, 0.0, 0.0, 0.0)
    слева = ground_to_pixel(0.0, 1.0, поза, intr, надир())   # Y влево
    assert слева[0] < intr.cx, "точка слева от дрона обязана быть левее центра кадра"


def test_поворот_курса_поворачивает_кадр():
    """Курс фиксируется в arm(), но проверить связь всё равно надо: на 90° влево
    то, что было впереди, обязано оказаться справа по кадру."""
    intr = оптика()
    впереди = ground_to_pixel(1.0, 0.0, Pose(0, 0, 2.0, 0, 0, 90.0), intr, надир())
    assert впереди[0] > intr.cx


def test_наклон_сервы_уводит_центр_вперёд():
    """При серве -80 камера смотрит на 10° вперёд от надира. Это ~35 см на 2 м —
    больше всего порога «<30 см», и знак сдвига обязан быть именно вперёд."""
    intr = оптика()
    поза = Pose(0.0, 0.0, 2.0, 0.0, 0.0, 0.0)
    центр = pixel_to_ground(intr.cx, intr.cy, поза, intr, рабочая())
    assert центр[0] == pytest.approx(2.0 * math.tan(math.radians(10.0)), abs=1e-6)
    assert центр[1] == pytest.approx(0.0, abs=1e-9)
    assert offset_from_nadir(поза, intr, рабочая()) == pytest.approx(0.353, abs=0.01)


def test_луч_вверх_землю_не_находит():
    """Камера, задранная выше горизонта, обязана вернуть None, а не станцию
    в километре от полигона."""
    intr = оптика()
    поза = Pose(0.0, 0.0, 2.0, 0.0, 0.0, 0.0)
    assert pixel_to_ground(intr.cx, intr.cy, поза, intr, mount_matrix(30.0)) is None


def test_дрон_на_земле_не_локализует():
    intr = оптика()
    assert pixel_to_ground(intr.cx, intr.cy, Pose(0, 0, 0.0, 0, 0, 0),
                           intr, надир()) is None


# --------------------------------------------------------------- бюджет ошибки

def test_медиана_наблюдений_укладывается_в_30_см():
    """Главная проверка пункта 2: одиночное наблюдение шумит, медиана — нет.

    Шум взят по бюджету docs/DRONE_PLAN.md §2.2: позиция дрона 10 см (оптопоток),
    ориентация 1°, высота 5 %, центроид 10 px. Все источники сразу.
    """
    случайное = random.Random(20260731)
    intr = оптика()
    истина = (1.4, -0.9)
    оценки = []
    # Дрон идёт полосой змейки прямо над станцией — так наблюдения и копятся в полёте.
    # Шаг 4.5 см — это скорость 0.45 м/с при инференсе 10 Гц, как в config.yaml.
    for шаг in range(40):
        правда = Pose(0.2 + 0.045 * шаг, истина[1], 2.0, 0.0, 0.0, 0.0)
        u, v = ground_to_pixel(истина[0], истина[1], правда, intr, рабочая())
        if not in_central_region(u, v, ШИРИНА, ВЫСОТА):
            continue
        шумная = Pose(
            правда.x + случайное.gauss(0, 0.10),
            правда.y + случайное.gauss(0, 0.10),
            правда.z * (1.0 + случайное.gauss(0, 0.05)),
            случайное.gauss(0, 1.0), случайное.gauss(0, 1.0), случайное.gauss(0, 1.0))
        точка = pixel_to_ground(u + случайное.gauss(0, 10), v + случайное.gauss(0, 10),
                                шумная, intr, рабочая())
        if точка is not None:
            оценки.append(точка)

    assert len(оценки) >= 10, "слишком мало наблюдений попало в центр кадра"
    оценки.sort(key=lambda p: p[0])
    медиана_x = оценки[len(оценки) // 2][0]
    оценки.sort(key=lambda p: p[1])
    медиана_y = оценки[len(оценки) // 2][1]
    ошибка = math.hypot(медиана_x - истина[0], медиана_y - истина[1])
    assert ошибка < 0.30, "медиана уехала на %.2f м — это потеря 4 баллов" % ошибка


def test_центр_кадра_точнее_края():
    """Обоснование правила «только центральные 50 %»: та же ошибка высоты у края
    кадра стоит заметно дороже, чем в центре."""
    intr = оптика()
    правда = Pose(0.0, 0.0, 2.0, 0.0, 0.0, 0.0)
    кривая = Pose(0.0, 0.0, 2.1, 0.0, 0.0, 0.0)      # высота завышена на 5 %

    def снос(u, v):
        a = pixel_to_ground(u, v, правда, intr, рабочая())
        b = pixel_to_ground(u, v, кривая, intr, рабочая())
        return math.hypot(a[0] - b[0], a[1] - b[1])

    assert снос(intr.cx, intr.cy) < снос(ШИРИНА - 20, intr.cy)


