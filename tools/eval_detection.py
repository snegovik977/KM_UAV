#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Оценка детекции и статусов по размеченной записи: единственный честный ответ
на вопрос «стало лучше или нет».

Без него подбор порогов превращается в «посмотрел на пару кадров — вроде получше»,
а на площадке это стоит попыток (регламент 1.3: лимит времени утекает, даже когда
полигон простаивает).

Разметка ожидается в формате YOLO — том же, в котором обучается модель, чтобы
не заводить второй формат:

    разметка/кадр_00042.txt      класс cx cy w h   (доли ширины/высоты кадра)
    кадры/кадр_00042.jpg

Печатает precision, recall, F1 и mAP@0.5 по детекции, а также confusion matrix
по трём статусам. Ошибка «ok <-> dust» стоит и 5 баллов подзадачи 2.3.3, и наведения
в 2.3.4, поэтому она смотрится отдельно, а не тонет в общей точности.

    python3 tools/eval_detection.py кадры/ разметка/
    python3 tools/eval_detection.py кадры/ разметка/ --set detector.min_area_m2=0.05
"""
from __future__ import annotations

import argparse
import glob
import os
import sys

_ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
_КОРЕНЬ = os.path.dirname(_ЗДЕСЬ)
for _путь in (_ЗДЕСЬ, _КОРЕНЬ, os.path.join(_КОРЕНЬ, "квадрокоптер")):
    if os.path.isdir(_путь) and _путь not in sys.path:
        sys.path.insert(0, _путь)

КЛАССЫ = ("ok", "dust", "broken")


def прочитать_разметку(path, ширина, высота):
    """YOLO-разметка -> [(класс, x1, y1, x2, y2)] в пикселях."""
    объекты = []
    if not os.path.exists(path):
        return объекты
    with open(path, "r") as f:
        for строка in f:
            части = строка.split()
            if len(части) < 5:
                continue
            класс = int(float(части[0]))
            cx, cy, w, h = (float(ч) for ч in части[1:5])
            объекты.append((класс,
                            (cx - w / 2) * ширина, (cy - h / 2) * высота,
                            (cx + w / 2) * ширина, (cy + h / 2) * высота))
    return объекты


def iou(a, b):
    x1 = max(a[0], b[0])
    y1 = max(a[1], b[1])
    x2 = min(a[2], b[2])
    y2 = min(a[3], b[3])
    пересечение = max(0.0, x2 - x1) * max(0.0, y2 - y1)
    площадь_a = max(0.0, a[2] - a[0]) * max(0.0, a[3] - a[1])
    площадь_b = max(0.0, b[2] - b[0]) * max(0.0, b[3] - b[1])
    объединение = площадь_a + площадь_b - пересечение
    return пересечение / объединение if объединение > 0 else 0.0


def сопоставить(детекции, истина, порог_iou):
    """Жадное сопоставление по убыванию уверенности. Возвращает пары и промахи."""
    пары = []
    свободные = list(range(len(истина)))
    лишние = []
    for детекция in sorted(детекции, key=lambda d: -d.score):
        бокс = детекция.bbox
        лучший, лучшее_iou = None, порог_iou
        for индекс in свободные:
            значение = iou(бокс, истина[индекс][1:])
            if значение >= лучшее_iou:
                лучший, лучшее_iou = индекс, значение
        if лучший is None:
            лишние.append(детекция)
        else:
            свободные.remove(лучший)
            пары.append((детекция, истина[лучший]))
    return пары, лишние, [истина[i] for i in свободные]


def средняя_точность(записи, всего_истинных):
    """AP по площади под кривой precision-recall (интерполяция «все точки»)."""
    if not записи or not всего_истинных:
        return 0.0
    записи = sorted(записи, key=lambda з: -з[0])
    попаданий = промахов = 0
    точки = []
    for _, попал in записи:
        if попал:
            попаданий += 1
        else:
            промахов += 1
        точки.append((попаданий / всего_истинных,
                      попаданий / max(1, попаданий + промахов)))
    # Сглаживаем справа налево: точность не может расти при росте полноты.
    лучшее = 0.0
    сглаженные = []
    for полнота, точность in reversed(точки):
        лучшее = max(лучшее, точность)
        сглаженные.append((полнота, лучшее))
    сглаженные.reverse()

    площадь = 0.0
    прошлая_полнота = 0.0
    for полнота, точность in сглаженные:
        площадь += (полнота - прошлая_полнота) * точность
        прошлая_полнота = полнота
    return площадь


def напечатать_матрицу(матрица):
    print("\nConfusion matrix по статусам (строки — истина, столбцы — предсказание):")
    заголовок = " " * 10 + "".join("%9s" % к for к in КЛАССЫ) + "%9s" % "нет"
    print(заголовок)
    for i, класс in enumerate(КЛАССЫ):
        строка = "%10s" % класс
        for j in range(len(КЛАССЫ) + 1):
            строка += "%9d" % матрица[i][j]
        print(строка)
    путаница = матрица[0][1] + матрица[1][0]
    if путаница:
        print("\n  ⚠️ ok <-> dust перепутано %d раз. Это и 5 баллов подзадачи 2.3.3, "
              "и наведение в 2.3.4: обдувать будут не ту станцию." % путаница)


def main():
    parser = argparse.ArgumentParser(description="mAP по детекции и статусам")
    parser.add_argument("frames", help="директория с кадрами")
    parser.add_argument("labels", help="директория с YOLO-разметкой")
    parser.add_argument("--config", default=None)
    parser.add_argument("--iou", type=float, default=0.5)
    parser.add_argument("--set", action="append", dest="правки", metavar="ПУТЬ=ЗНАЧЕНИЕ")
    args = parser.parse_args()

    import cv2

    import config as config_module
    from perception.detector import create_detector
    from replay import применить_правки

    cfg = config_module.load(args.config)
    применить_правки(cfg, args.правки)
    детектор = create_detector(cfg, log=print)

    пути = sorted(glob.glob(os.path.join(args.frames, "*.jpg"))
                  + glob.glob(os.path.join(args.frames, "*.png")))
    if not пути:
        print("В %s нет кадров" % args.frames)
        return 1

    записи_ap = []
    всего_истинных = 0
    попаданий = лишних = пропущено = 0
    матрица = [[0] * (len(КЛАССЫ) + 1) for _ in КЛАССЫ]

    for путь in пути:
        кадр = cv2.imread(путь)
        if кадр is None:
            continue
        высота, ширина = кадр.shape[:2]
        имя = os.path.splitext(os.path.basename(путь))[0] + ".txt"
        истина = прочитать_разметку(os.path.join(args.labels, имя), ширина, высота)
        всего_истинных += len(истина)

        # Площадь в м² тут не считается: позы дрона у отдельного кадра нет.
        # Значит фильтр по размеру не работает, и оценка получается пессимистичной —
        # это честнее, чем подсунуть выдуманную высоту.
        детекции = детектор.detect(кадр)
        пары, лишние, промахи = сопоставить(детекции, истина, args.iou)

        попаданий += len(пары)
        лишних += len(лишние)
        пропущено += len(промахи)
        for детекция, _ in пары:
            записи_ap.append((детекция.score, True))
        for детекция in лишние:
            записи_ap.append((детекция.score, False))

        for детекция, эталон in пары:
            истинный = эталон[0]
            if 0 <= истинный < len(КЛАССЫ):
                предсказанный = (КЛАССЫ.index(детекция.label)
                                 if детекция.label in КЛАССЫ else len(КЛАССЫ))
                матрица[истинный][предсказанный] += 1

    точность = попаданий / max(1, попаданий + лишних)
    полнота = попаданий / max(1, всего_истинных)
    f1 = 2 * точность * полнота / max(1e-9, точность + полнота)

    print("\nКадров: %d, размеченных объектов: %d" % (len(пути), всего_истинных))
    print("Найдено верно: %d, лишних: %d, пропущено: %d"
          % (попаданий, лишних, пропущено))
    print("Precision %.3f, Recall %.3f, F1 %.3f, mAP@%.1f %.3f"
          % (точность, полнота, f1, args.iou,
             средняя_точность(записи_ap, всего_истинных)))
    if лишних:
        print("\n  ⚠️ Лишние детекции опаснее пропусков не меньше: условие всех "
              "8 баллов подзадачи 2.3.2 — совпадение ЧИСЛА станций с реальным.")
    напечатать_матрицу(матрица)
    return 0


if __name__ == "__main__":
    sys.exit(main())
