# -*- coding: utf-8 -*-
"""Пиксель кадра -> точка на земле в нашей СК. Это и есть 4 балла за точность.

Критерий подзадачи 2.3.2: «координаты станции на карте визуализатора отличаются
от реальных менее чем на 30 см». Вся цепочка ошибок описана в docs/DRONE_PLAN.md §2.2;
здесь — формула и правило отбора наблюдений, которое из этого бюджета следует.

Модуль **не зависит ни от чего**: ни SDK, ни cv2, ни numpy. Матрицы 3x3 — обычные
кортежи. Так он целиком проверяется тестами на любой машине (регламент 1.3: лимит
времени утекает, даже когда полигон простаивает), и импорт не может отвалиться там,
где сломался OpenCV.

СИСТЕМЫ КООРДИНАТ, три штуки. Путать их — главный способ получить правдоподобные,
но неверные координаты, поэтому они выписаны явно:

  МИР (наша СК)   X вперёд, Y влево, Z вверх. Начало — точка взлёта. Правая.
                  В ней живут пакеты протокола и карта визуализатора.
  КОРПУС          та же тройка осей, но повёрнутая вместе с дроном.
  КАМЕРА          x вправо по кадру, y вниз по кадру, z вдоль оптической оси
                  (стандарт OpenCV). Пересчёт «камера -> корпус» — это R_mount
                  из perception/calib.py, и он зависит от угла сервопривода.

Углы всюду в ГРАДУСАХ, повороты правые (по правилу правой руки вокруг своей оси):
  roll  вокруг +X (вперёд):  +Y -> +Z, то есть положительный roll поднимает левый борт;
  pitch вокруг +Y (влево):   +Z -> +X, то есть положительный pitch опускает нос;
  yaw   вокруг +Z (вверх):   +X -> +Y, то есть положительный yaw — поворот влево.

⚠️ В какой знаковой конвенции отдаёт углы get_orientation() нашего борта — НЕ ПРОВЕРЕНО.
Поэтому знаки roll и pitch выведены в config.yaml (camera.attitude.*): ошибка знака
не падает с исключением, она удваивает вклад крена в ошибку координат (~3.5 см на градус,
docs/DRONE_PLAN.md §2.2). На рабочей высоте дрон летит почти ровно, так что это не
блокирует пункт 2, но закрыть вопрос надо — см. RUN.md.
"""
from __future__ import annotations

import math
from collections import namedtuple

# Поза дрона в мире: метры и градусы. Ровно то, что отдаёт Flight.position()
# и Flight.orientation().
Pose = namedtuple("Pose", "x y z roll pitch yaw")

# Луч, идущий вверх или строго горизонтально, землю не пересекает. Порог не ноль:
# при делении на почти-ноль t улетает в километры, и такое наблюдение — мусор,
# который обязан быть отброшен, а не занесён в реестр.
_МИН_НАКЛОН = 1e-3


# ----------------------------------------------------------------- матрицы 3x3

def matmul(a, b):
    """Произведение двух матриц 3x3, заданных кортежами строк."""
    return tuple(
        tuple(sum(a[i][k] * b[k][j] for k in range(3)) for j in range(3))
        for i in range(3)
    )


def matvec(m, v):
    return tuple(sum(m[i][k] * v[k] for k in range(3)) for i in range(3))


def transpose(m):
    """Для матрицы поворота транспонирование — это обратный поворот."""
    return tuple(tuple(m[j][i] for j in range(3)) for i in range(3))


def rot_x(deg):
    c, s = math.cos(math.radians(deg)), math.sin(math.radians(deg))
    return ((1.0, 0.0, 0.0),
            (0.0, c, -s),
            (0.0, s, c))


def rot_y(deg):
    c, s = math.cos(math.radians(deg)), math.sin(math.radians(deg))
    return ((c, 0.0, s),
            (0.0, 1.0, 0.0),
            (-s, 0.0, c))


def rot_z(deg):
    c, s = math.cos(math.radians(deg)), math.sin(math.radians(deg))
    return ((c, -s, 0.0),
            (s, c, 0.0),
            (0.0, 0.0, 1.0))


def attitude_matrix(roll, pitch, yaw):
    """Поворот «корпус -> мир» по углам дрона. Порядок Z-Y-X (рыскание снаружи)."""
    return matmul(rot_z(yaw), matmul(rot_y(pitch), rot_x(roll)))


def pose_matrix(pose):
    return attitude_matrix(pose.roll, pose.pitch, pose.yaw)


# ------------------------------------------------------------ пиксель -> земля

def pixel_to_ground(u, v, pose, intr, r_mount, ground_z=0.0):
    """Куда на земле смотрит пиксель (u, v). Возвращает (X, Y) в мире или None.

    None означает «луч не пересекает землю»: камера смотрит вверх или почти вдоль
    горизонта. Такое наблюдение обязано быть отброшено, а не превращено в станцию
    в километре от полигона.

    ground_z — высота плоскости земли в нашей СК. Ноль почти всегда: начало отсчёта
    на посадочной площадке, и станции стоят на том же полу.
    """
    xn, yn = intr.normalize(u, v)
    d_cam = (xn, yn, 1.0)
    d_world = matvec(matmul(pose_matrix(pose), r_mount), d_cam)

    высота = pose.z - ground_z
    if высота <= 0.0:
        return None                      # дрон на земле или ниже неё — смысла нет
    if d_world[2] >= -_МИН_НАКЛОН:
        return None                      # луч не идёт вниз

    t = высота / (-d_world[2])
    return (pose.x + t * d_world[0], pose.y + t * d_world[1])


def ground_to_pixel(x, y, pose, intr, r_mount, ground_z=0.0):
    """Обратная задача: в каком пикселе видна точка земли (X, Y). None — вне кадра.

    Нужна не только тестам: этой же формулой заглушка камеры рисует станции
    (mock_pioneer.py), поэтому сквозной прогон «мок -> детекция -> координаты»
    проверяет прямую формулу против обратной.
    """
    в_мире = (x - pose.x, y - pose.y, ground_z - pose.z)
    d_cam = matvec(transpose(matmul(pose_matrix(pose), r_mount)), в_мире)
    if d_cam[2] <= _МИН_НАКЛОН:
        return None                      # точка позади камеры или в её плоскости
    return intr.project(d_cam[0] / d_cam[2], d_cam[1] / d_cam[2])


# --------------------------------------------------- отбор и метрика наблюдений

def in_central_region(u, v, width, height, frac=0.5):
    """Лежит ли пиксель в центральных frac кадра по каждой оси.

    Правило из бюджета ошибки (docs/DRONE_PLAN.md §2.2): вклад ошибки высоты
    пропорционален удалению объекта от центра кадра. У нас надира нет — сервопривод
    ограничен -80° (docs/lessons_from_archipelago.md §1.1), — поэтому правило
    обязательное, а не желательное: наблюдения от краёв кадра тянут медиану за порог.
    """
    if not 0.0 < frac <= 1.0:
        raise ValueError("frac должно быть в (0, 1], получено %r" % (frac,))
    половина = frac / 2.0
    return (abs(u - width / 2.0) <= width * половина
            and abs(v - height / 2.0) <= height * половина)


def polygon_area(points):
    """Площадь многоугольника по формуле шнурования, м²."""
    площадь = 0.0
    for (x1, y1), (x2, y2) in zip(points, points[1:] + points[:1]):
        площадь += x1 * y2 - x2 * y1
    return abs(площадь) / 2.0


def ground_area(corners, pose, intr, r_mount, ground_z=0.0):
    """Площадь объекта на земле в м² по его углам в пикселях. None, если любой
    угол не проецируется на землю.

    Площадь в пикселях порогом быть не может: она падает с высотой квадратично,
    и порог, подобранный на 1.5 м, отсечёт ту же станцию на 2 м. Порог в м² —
    свойство самой станции и от высоты не зависит (регламент 2.5).
    """
    на_земле = []
    for u, v in corners:
        точка = pixel_to_ground(u, v, pose, intr, r_mount, ground_z)
        if точка is None:
            return None
        на_земле.append(точка)
    if len(на_земле) < 3:
        return None
    return polygon_area(на_земле)


def offset_from_nadir(pose, intr, r_mount, ground_z=0.0):
    """На сколько метров центр кадра уехал от точки прямо под дроном.

    Диагностика, а не часть алгоритма: при servo_angle=-80 на высоте 2 м это ~35 см,
    то есть больше всего порога «<30 см». Печатается при старте, чтобы забытая
    поправка R_mount была видна на земле, а не в протоколе попытки.
    """
    центр = pixel_to_ground(intr.cx, intr.cy, pose, intr, r_mount, ground_z)
    if центр is None:
        return None
    return math.hypot(центр[0] - pose.x, центр[1] - pose.y)
