# -*- coding: utf-8 -*-
"""Перевод наших пакетов в текстовый формат из примера организаторов.

Организаторы прислали рабочий визуализатор (source/2_step/MapExample.py). Он ждёт
совсем другого, чем наш протокол:

    POST /fly     тело "x,y" — координаты в ПИКСЕЛЯХ карты, либо "reset"
    POST /eyecar  тело "Good" | "Broken", либо "1".."5" — стадии зарядки

Тело — голая строка, не JSON. Такой формат не везёт ни идентификатор станции, ни трёх
статусов регламента (только Good/Broken, а «покрыта пылью» — третий), ни номера пакета,
по которому отсеиваются повторы. Поэтому наш протокол остаётся как есть, а этот модуль —
мост наружу: если на площадке окажется визуализатор смежного трека, написанный по
примеру организаторов, хаб дотянется и до него (hub.py --forward).

Здесь же живёт привязка «метры нашей СК -> пиксели карты»: пример организаторов
станции просто захардкодил, а у нас они приходят от дрона в метрах.

Модуль на стандартной библиотеке: его импортируют и хаб, и визуализатор, и тесты.
"""
from __future__ import annotations

import math

# Куда наши три статуса отображаются в двоичный Good/Broken примера организаторов.
# «Покрыта пылью» — станция рабочая, просто требует очистки, и терять её из маршрута
# автомобиля было бы хуже, чем не сообщить про пыль.
СТАТУС_В_ТЕКСТ = {"ok": "Good", "dust": "Good", "broken": "Broken"}


class MapAnchor(object):
    """Привязка карты: метры нашей СК -> пиксели картинки полигона.

    Три числа задают её полностью: где на картинке находится точка взлёта дрона,
    сколько пикселей в метре и как повёрнута карта относительно нашей оси X.

    Меряется один раз на площадке по картинке: взять две точки с известным расстоянием
    между ними (например, углы посадочной площадки), посчитать масштаб, отметить
    пиксель точки взлёта. Всё три числа — в config.yaml -> map, в коде их быть не должно
    (регламент 2.5).
    """

    def __init__(self, px_per_m=100.0, origin_px=(0, 0), yaw_deg=0.0,
                 width=None, height=None):
        if px_per_m <= 0:
            raise ValueError("px_per_m должно быть положительным, получено %r" % (px_per_m,))
        self.px_per_m = float(px_per_m)
        self.origin_px = (float(origin_px[0]), float(origin_px[1]))
        self.yaw_deg = float(yaw_deg)
        self.width = width
        self.height = height

    @classmethod
    def from_config(cls, cfg, width=None, height=None):
        раздел = cfg.get("map", {}) if hasattr(cfg, "get") else {}
        origin_x = float(раздел.get("origin_px_x", (width or 0) / 2.0))
        origin_y = float(раздел.get("origin_px_y", (height or 0) / 2.0))
        return cls(px_per_m=float(раздел.get("px_per_m", 100.0)),
                   origin_px=(origin_x, origin_y),
                   yaw_deg=float(раздел.get("yaw_deg", 0.0)),
                   width=width, height=height)

    def to_px(self, x, y):
        """Метры (X вперёд, Y влево) -> пиксели карты (столбец, строка).

        Ось строк изображения растёт вниз, а наша Y — влево, поэтому знаки разные:
        вперёд по X — это вверх по картинке, влево по Y — влево по картинке.
        """
        угол = math.radians(self.yaw_deg)
        вперёд = x * math.cos(угол) - y * math.sin(угол)
        влево = x * math.sin(угол) + y * math.cos(угол)
        u = self.origin_px[0] - влево * self.px_per_m
        v = self.origin_px[1] - вперёд * self.px_per_m
        return int(round(u)), int(round(v))

    def to_meters(self, u, v):
        """Обратно: пиксели карты -> метры. Нужна, чтобы отметить точку взлёта мышью
        по картинке и получить готовые числа для конфига."""
        влево = (self.origin_px[0] - u) / self.px_per_m
        вперёд = (self.origin_px[1] - v) / self.px_per_m
        угол = math.radians(-self.yaw_deg)
        x = вперёд * math.cos(угол) - влево * math.sin(угол)
        y = вперёд * math.sin(угол) + влево * math.cos(угол)
        return x, y

    def inside(self, u, v):
        """Попадает ли пиксель в картинку. Пример организаторов на выход за границы
        падает с IndexError, поэтому проверяем сами и не шлём заведомо битое."""
        if self.width is None or self.height is None:
            return True
        return 0 <= u < self.width and 0 <= v < self.height


def to_legacy(msg, anchor):
    """Наш пакет -> список (маршрут, тело) для примера организаторов.

    Пустой список означает «этому пакету в том формате соответствия нет» — например,
    телеметрии дрона там просто некуда лечь.
    """
    тип = msg.get("type")
    data = msg.get("data", {})

    if тип == "station_new":
        u, v = anchor.to_px(data["x"], data["y"])
        if not anchor.inside(u, v):
            return []
        отправления = [("/fly", "%d,%d" % (u, v))]
        текст = СТАТУС_В_ТЕКСТ.get(data.get("status"))
        if текст:
            отправления.append(("/eyecar", текст))
        return отправления

    if тип == "status_update":
        текст = СТАТУС_В_ТЕКСТ.get(data.get("status"))
        # ⚠️ /eyecar в примере организаторов НЕ несёт идентификатора: он красит
        # станции по порядку прихода сообщений (stations_counter). Значит статус
        # уедет не на ту станцию, если порядок разойдётся. Наш собственный
        # визуализатор ведёт станции по id и этой болезнью не страдает.
        return [("/eyecar", текст)] if текст else []

    return []
