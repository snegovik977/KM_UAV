#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Размеченные клипы -> датасет ultralytics (train/val) + data.yaml.

Третий шаг конвейера (docs/YOLO_TRAINING.md §4). Идемпотентно: пересобирает
training/dataset целиком, поэтому «разметили ещё сотню кадров» — это просто
повторный запуск.

Два правила, ради которых скрипт вообще существует.

1. **Сплит train/val — ПО КЛИПАМ, а не по кадрам.** Соседние кадры одного пролёта
   отличаются на дрожание руки. При случайном разбиении они попадают и в train,
   и в val, модель их запоминает, и val-метрика показывает 0.95 на сети, которая
   на площадке не видит ничего. Это не теория: ровно на этом обжигалась команда
   с того же соревнования (docs/lessons_from_archipelago.md §4).

2. **В датасет идёт только кадр, у которого ЕСТЬ .txt.** Кадр без .txt — не негатив,
   а «ещё не смотрели»; попав в обучение, он учит сеть не видеть станцию там, где
   она есть. Пустой .txt, наоборот, — полноценный проверенный негатив и берётся.

Плюс сверка с бортом: список классов из classes.txt должен совпадать с
detector.labels в квадрокоптер/config.yaml, иначе декодер на борту разложит
выходы модели не по тем каналам — молча, без единой ошибки.

    python training/build_dataset.py
    python training/build_dataset.py --val-clips 083847,organizers
"""
from __future__ import annotations

import argparse
import os
import shutil
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common                                                      # noqa: E402


def прочитать_val_клипы(путь=None, аргумент=None):
    """Какие клипы уходят в val: ключ --val-clips либо файл training/val_clips.txt."""
    if аргумент:
        return [ч.strip() for ч in аргумент.split(",") if ч.strip()]
    путь = путь or common.ФАЙЛ_VAL
    if not os.path.exists(путь):
        return []
    with open(путь, "rb") as f:
        return [с.strip() for с in f.read().decode("utf-8").splitlines()
                if с.strip() and not с.strip().startswith("#")]


def выбрать_val(все_клипы, заданные, log=print):
    """Клипы для val. Если не заданы — берётся каждый третий по счёту.

    Автовыбор намеренно тупой и воспроизводимый: он не смотрит на содержимое,
    поэтому не может «подобрать» удобный val. Правильный val выбирает человек —
    тот клип, который больше похож на зачётную попытку.
    """
    if заданные:
        неизвестные = [к for к in заданные if к not in все_клипы]
        if неизвестные:
            log("⚠ в images_to_label нет клипов: %s" % ", ".join(неизвестные))
        return [к for к in заданные if к in все_клипы]
    if len(все_клипы) < 2:
        log("⚠ клип всего один: val = train, метрика будет врать. Снимите ещё серию")
        return []
    return все_клипы[2::3] or все_клипы[-1:]


def собрать(корень_разметки, куда, val_клипы, имена_классов, log=print):
    """Копирует кадры с разметкой в dataset/{images,labels}/{train,val}."""
    if os.path.isdir(куда):
        shutil.rmtree(куда)
    for раздел in ("train", "val"):
        os.makedirs(os.path.join(куда, "images", раздел))
        os.makedirs(os.path.join(куда, "labels", раздел))

    статистика = {"train": {}, "val": {}}
    брак = []
    для_классов = [0] * len(имена_классов)

    for клип in common.клипы(корень_разметки):
        раздел = "val" if клип in val_клипы else "train"
        папка = os.path.join(корень_разметки, клип)
        for картинка in common.файлы(папка, common.РАСШИРЕНИЯ_КАРТИНОК):
            txt = os.path.splitext(картинка)[0] + ".txt"
            if not os.path.exists(txt):
                continue                   # не размечено — в датасет не идёт
            try:
                боксы = common.читать_разметку(txt)
            except ValueError as e:
                брак.append((txt, str(e)))
                continue
            причины = [common.проверить_бокс(б, len(имена_классов)) for б in боксы]
            причины = [п for п in причины if п]
            if причины:
                брак.append((txt, "; ".join(причины[:3])))
                continue

            имя = os.path.basename(картинка)
            # Имя клипа в имени файла: кадры разных клипов могут называться
            # одинаково, а в dataset/ они лежат одной кучей.
            цель = "%s__%s" % (клип, имя)
            shutil.copy2(картинка, os.path.join(куда, "images", раздел, цель))
            shutil.copy2(txt, os.path.join(куда, "labels", раздел,
                                           os.path.splitext(цель)[0] + ".txt"))
            запись = статистика[раздел].setdefault(
                клип, {"кадров": 0, "боксов": 0, "пустых": 0})
            запись["кадров"] += 1
            запись["боксов"] += len(боксы)
            запись["пустых"] += 1 if not боксы else 0
            for бокс in боксы:
                для_классов[бокс[0]] += 1
    return статистика, брак, для_классов


def написать_data_yaml(куда, имена_классов):
    """data.yaml для ultralytics. Путь абсолютный: ultralytics ищет датасет
    относительно своей настройки datasets_dir, а не относительно файла."""
    путь = os.path.join(куда, "data.yaml")
    строки = ["# Сгенерирован training/build_dataset.py — руками не править,",
              "# классы берутся из training/classes.txt.",
              "path: %s" % os.path.abspath(куда),
              "train: images/train",
              "val: images/val",
              "",
              "nc: %d" % len(имена_классов),
              "names:"]
    строки += ["  %d: %s" % (i, имя) for i, имя in enumerate(имена_классов)]
    with open(путь, "wb") as f:
        f.write(("\n".join(строки) + "\n").encode("utf-8"))
    return путь


def отчёт(статистика, брак, для_классов, имена_классов, log=print):
    log("%-6s %-16s %7s %7s %7s" % ("раздел", "клип", "кадров", "боксов", "пустых"))
    итоги = {}
    for раздел in ("train", "val"):
        for клип, з in sorted(статистика[раздел].items()):
            log("%-6s %-16s %7d %7d %7d"
                % (раздел, клип, з["кадров"], з["боксов"], з["пустых"]))
        итоги[раздел] = (sum(з["кадров"] for з in статистика[раздел].values()),
                         sum(з["боксов"] for з in статистика[раздел].values()),
                         sum(з["пустых"] for з in статистика[раздел].values()))
    log("")
    log("TRAIN: %d кадров, %d боксов, %d пустых | VAL: %d кадров, %d боксов, %d пустых"
        % (итоги["train"] + итоги["val"]))
    log("по классам: %s" % ", ".join("%s=%d" % (имя, число)
                                     for имя, число in zip(имена_классов, для_классов)))

    всего_кадров = итоги["train"][0] + итоги["val"][0]
    всего_боксов = sum(для_классов)
    if брак:
        log("")
        log("⚠ пропущено файлов с негодной разметкой: %d" % len(брак))
        for путь, причина in брак[:10]:
            log("   %s: %s" % (os.path.basename(путь), причина))

    # Предупреждения, которые дешевле прочитать сейчас, чем искать потом в mAP.
    log("")
    if итоги["val"][0] == 0:
        log("⚠ val пуст: метрике неоткуда взяться. Задайте --val-clips")
    if всего_кадров < 150:
        log("⚠ кадров всего %d. Рабочий минимум — около 300, иначе сеть выучит "
            "конкретные кадры, а не станцию" % всего_кадров)
    пустых = итоги["train"][2] + итоги["val"][2]
    if всего_кадров and пустых * 5 < всего_кадров:
        log("⚠ негативов (кадров без станций) всего %d из %d. Ложные срабатывания "
            "лечатся именно ими: логотип на полу, разметка, мусор" % (пустых, всего_кадров))
    if всего_боксов:
        редкий = min(для_классов)
        if редкий * 5 < всего_боксов:
            имя = имена_классов[для_классов.index(редкий)]
            log("⚠ класс %r встречается %d раз из %d боксов — он не выучится. "
                "Доснять и разметить" % (имя, редкий, всего_боксов))


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--dir", default=common.ПАПКА_РАЗМЕТКИ)
    parser.add_argument("--out", default=common.ПАПКА_ДАТАСЕТА)
    parser.add_argument("--val-clips", default=None,
                        help="клипы в val через запятую; иначе training/val_clips.txt")
    аргументы = parser.parse_args()

    имена = common.классы()
    метки_борта = common.метки_из_конфига()
    if метки_борта is not None and метки_борта != имена:
        print("⚠ РАСХОЖДЕНИЕ С БОРТОМ: classes.txt = %s, а detector.labels "
              "в config.yaml = %s. Декодер на борту разбирает выходы модели по числу "
              "классов — при расхождении боксы будут неверными БЕЗ единой ошибки."
              % (имена, метки_борта))

    клипы = common.клипы(аргументы.dir)
    if not клипы:
        print("в %s нет клипов: сначала extract_frames.py, потом label.py" % аргументы.dir)
        return 1
    # Клип может быть размечен и при этом негоден для обучения — например, снят
    # телефоном, а не камерой борта: другая оптика и масштаб. Удалять такой жалко
    # (по нему сверяют разметку глазами), поэтому он просто исключается списком.
    пропустить = прочитать_val_клипы(путь=common.ФАЙЛ_SKIP)
    if пропустить:
        print("пропускаю (skip_clips.txt): %s" % ", ".join(пропустить))
        клипы = [к for к in клипы if к not in пропустить]
        if not клипы:
            print("после пропуска не осталось ни одного клипа")
            return 1
    val = выбрать_val(клипы, прочитать_val_клипы(аргумент=аргументы.val_clips))
    print("клипы: %s" % ", ".join(клипы))
    print("в val: %s" % (", ".join(val) if val else "(нет)"))
    print("")

    статистика, брак, для_классов = собрать(аргументы.dir, аргументы.out, val, имена)
    отчёт(статистика, брак, для_классов, имена)
    путь = написать_data_yaml(аргументы.out, имена)
    print("")
    print("data.yaml: %s" % путь)
    print("Дальше: python training/train.py")
    return 0


if __name__ == "__main__":
    sys.exit(main())
